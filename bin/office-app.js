// `sm app`: builds the office as a real Mac app ("AI Office.app") and pins it to the Dock.
// It is a small native AppKit program (office-app/main.swift, compiled with `swiftc` — no Xcode project)
// showing the office in its own window via WebKit: no browser. It starts the office server if it is asleep
// (never rebuilds/restarts a running one), signs in with the private token and reconnects after restarts.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const NAME = 'AI Office';
const BUNDLE_ID = 'dev.throngs.ai-office';

const launcherScript = (node) => `#!/bin/bash
# AI Office launcher (generated by \`sm app\`). Wakes the office: starts it if needed, then opens it.
export PATH="${path.dirname(node)}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
cd "${ROOT}" || exit 1
exec "${node}" bin/sm.js office >> "${ROOT}/.pixel-office-app.log" 2>&1
`;

const plist = () => `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleName</key><string>${NAME}</string>
<key>CFBundleDisplayName</key><string>${NAME}</string>
<key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
<key>CFBundleExecutable</key><string>${NAME}</string>
<key>CFBundleIconFile</key><string>AppIcon</string>
<key>CFBundlePackageType</key><string>APPL</string>
<key>CFBundleVersion</key><string>1</string>
<key>CFBundleShortVersionString</key><string>1.0</string>
<key>LSMinimumSystemVersion</key><string>13.0</string>
<key>NSAppTransportSecurity</key><dict><key>NSAllowsLocalNetworking</key><true/></dict>
<key>NSHighResolutionCapable</key><true/>
</dict></plist>
`;

function run(cmd, args) {
  const r = spawnSync(cmd, args, { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`${cmd} ${args[0]} failed: ${(r.stderr || r.stdout || '').trim().slice(0, 300)}`);
  return r.stdout;
}

function buildIcns(png, out) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aioffice-'));
  const set = path.join(tmp, 'AppIcon.iconset');
  fs.mkdirSync(set);
  for (const s of [16, 32, 128, 256, 512]) {
    run('sips', ['-z', String(s), String(s), png, '--out', path.join(set, `icon_${s}x${s}.png`)]);
    run('sips', ['-z', String(s * 2), String(s * 2), png, '--out', path.join(set, `icon_${s}x${s}@2x.png`)]);
  }
  run('iconutil', ['-c', 'icns', set, '-o', out]);
  fs.rmSync(tmp, { recursive: true, force: true });
}

/** The Chrome profile signed in as the owner (SM_OWNER_EMAIL); "Default" if unknown. */
function chromeProfile() {
  const owner = process.env.SM_OWNER_EMAIL || '';
  try {
    const st = JSON.parse(fs.readFileSync(path.join(os.homedir(), 'Library', 'Application Support', 'Google', 'Chrome', 'Local State'), 'utf8'));
    const hit = Object.entries(st.profile?.info_cache || {}).find(([, v]) => String(v.user_name || '').toLowerCase() === owner.toLowerCase());
    return hit ? hit[0] : 'Default';
  } catch { return 'Default'; }
}

/** Compile the native app: the Swift source + a generated config with this machine's paths. */
function compileApp(out) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aioffice-src-'));
  const cfg = path.join(tmp, 'Config.swift');
  const str = (v) => JSON.stringify(String(v)); // valid Swift string literal for plain paths
  const PATH = [path.dirname(process.execPath), '/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin'].join(':');
  fs.writeFileSync(cfg, `enum OfficeConfig {\n  static let root = ${str(ROOT)}\n  static let node = ${str(process.execPath)}\n  static let path = ${str(PATH)}\n  static let port = 4777\n  static let chromeProfile = ${str(chromeProfile())}\n}\n`);
  const r = spawnSync('swiftc', ['-O', '-target', `${process.arch === 'arm64' ? 'arm64' : 'x86_64'}-apple-macos13.0`,
    '-framework', 'AppKit', '-framework', 'WebKit', '-o', out, path.join(ROOT, 'office-app', 'main.swift'), cfg], { encoding: 'utf8' });
  fs.rmSync(tmp, { recursive: true, force: true });
  if (r.status !== 0) throw new Error(`Building the app failed (swiftc):\n${(r.stderr || r.stdout || '').trim().slice(0, 1500)}`);
}

function install(dest) {
  const app = path.join(dest, `${NAME}.app`);
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(path.join(app, 'Contents', 'MacOS'), { recursive: true });
  fs.mkdirSync(path.join(app, 'Contents', 'Resources'));
  fs.writeFileSync(path.join(app, 'Contents', 'Info.plist'), plist());
  compileApp(path.join(app, 'Contents', 'MacOS', NAME));
  const icon = path.join(ROOT, 'pixel-office', 'webview-ui', 'public', 'icons', 'icon-512.png');
  buildIcns(icon, path.join(app, 'Contents', 'Resources', 'AppIcon.icns'));
  spawnSync('codesign', ['--force', '--sign', '-', app]);
  spawnSync('touch', [app]);
  return app;
}

function pinToDock(app) {
  const dock = run('defaults', ['read', 'com.apple.dock', 'persistent-apps']);
  if (dock.includes(`${NAME}.app`) || dock.includes(`${encodeURIComponent(NAME)}.app`)) return false; // the Dock may store "AI%20Office.app"
  const entry = `<dict><key>tile-data</key><dict><key>file-data</key><dict><key>_CFURLString</key><string>${app}/</string><key>_CFURLStringType</key><integer>0</integer></dict></dict></dict>`;
  run('defaults', ['write', 'com.apple.dock', 'persistent-apps', '-array-add', entry]);
  spawnSync('killall', ['Dock']);
  return true;
}

// Never rewrite the Dock's prefs to remove an icon: a full round-trip of com.apple.dock once left the Dock unable to
// start. Removing it is one right-click for the owner (Options → Remove from Dock).
function unpinFromDock() {
  const dock = spawnSync('defaults', ['read', 'com.apple.dock', 'persistent-apps'], { encoding: 'utf8' }).stdout || '';
  return dock.includes(`${NAME}.app`) || dock.includes(`${encodeURIComponent(NAME)}.app`);
}

function main(flags = {}) {
  if (process.platform !== 'darwin') throw new Error('sm app only works on macOS.');
  if (flags.uninstall) {
    const app = path.join(os.homedir(), 'Applications', `${NAME}.app`);
    const pinned = unpinFromDock();
    fs.rmSync(app, { recursive: true, force: true });
    console.log(`Removed ${app}.${pinned ? ` Its Dock icon stays until you right-click it → Options → Remove from Dock.` : ''}`);
    return;
  }
  const dest = flags.dest ? path.resolve(String(flags.dest)) : path.join(os.homedir(), 'Applications');
  fs.mkdirSync(dest, { recursive: true });
  const app = install(dest);
  console.log(`📦 Installed ${app}`);
  if (flags['no-dock']) return;
  console.log(pinToDock(app) ? '📌 Pinned to your Dock — tap the icon to wake the office.' : '📌 Already in your Dock.');
}

module.exports = { main, install, compileApp, pinToDock, unpinFromDock, launcherScript };
